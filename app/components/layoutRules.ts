// 화면 폭에 따라 크기·배치가 바뀌는 규칙은 전부 여기 상수를 쓴다. 이 파일을
// 거치지 않고 컴포넌트 안에서 숫자를 직접 비교하지 말 것 — 예전에 480/620 두
// 기준선이 안마다 따로 굴러다니면서 같은 폭에서 안끼리 다르게 보이는 문제가
// 있었다.
//
// ── 폭 기준선은 620 하나 ─────────────────────────────────────────────────────
// 폰 세로(360~619)와 그보다 넓은 화면(태블릿·가로·폴더블, 620+)을 가르는 값.
// 폭만 보면 되는 분기는 전부 이 값을 쓴다:
//   · 홈  1단(max HOME_W_1COL) ↔ 2단(max HOME_W_2COL)   app/home/page.tsx
//
// ── 카메라 목록 방향은 폭으로 정하지 않는다 ──────────────────────────────────
// 목록이 가로 한 줄이냐 세로 2열이냐는 '남은 세로'에 달려 있어서 폭 기준선으로는
// 못 가른다(620px 이라도 4:5 처럼 세로로 긴 화면은 세로 2열이 넉넉히 들어간다).
// 기준: 세로 2열로 '완전히 보이는 2개 + 반쯤 보이는 2개'(= 1.5줄)에 못 미치면
// 가로 한 줄로 넘어간다. app/components/useListLayout.ts 하나를 안들이 공유한다.
//
// 가로 한 줄일 때 목록 영역 높이 = '움직임 감지' 탭 높이(MOTION_MIN_H). '최소'가
// 아니라 '정확히 그 값'으로 못 박는다 — 두 탭 스트립이 1px 도 안 어긋나야 하므로,
// 세로가 남는 화면(620×780·750×832)에서 목록만 flex-1 로 늘어나면 안 된다.
// 못 박고 남는 세로는 단일 영상이 가져간다(아래 참고) — 스트립 아래에 빈 공간을
// 남기지 않는다. 실시간·녹화 모두 같다.
// A안 얘기다 — A-1·B안의 감지 탭은 '세로 타임라인'이라 영역을 채우는 게 맞고,
// 그래서 useListLayout 에 motionH 를 안 넘긴다(못 박지도, 영상을 늘리지도 않는다).
//
// ── 단일 영상(큰 영상)은 기본이 정확히 16:9 ─────────────────────────────────
// 구현은 globals.css 의 .single-video-area / .single-video-box. 영역은 16:9 높이
// (56.25cqw = 프레임폭×9/16)를 기본 크기로 잡고 늘어나지는 않으며, 자리가 모자랄
// 때만 줄어든다. 박스는 그 높이를 채우되 폭이 비율을 따라가므로 비율이 안 깨진다.
// cqw 는 .app-safe-frame 의 컨테이너 폭 기준이라 데스크톱 미리보기·실기기 모두에서
// JS 측정 없이 정확하다.
//
//   ※ 예외 — 카메라 목록이 가로 스크롤(가로 한 줄)일 때는 16:9 를 넘겨 늘어난다.
//     목록 스트립을 MOTION_MIN_H 로 못 박고 남는 세로를 영상이 다 가져가기 때문이다
//     (useListLayout 이 .single-video-area 의 flex-grow / max-height 를 푼다).
//     프리셋 기준 620×780 에서 1.52:1(녹화)·1.22:1(실시간)까지 세로로 늘어난다.
//     예전엔 '비율 유지'를 택해 그 자리를 빈 공간으로 뒀는데, 감지 탭과 목록 탭이
//     같은 높이여야 한다는 요구와 겹치면서 빈 공간이 눈에 띄어 뒤집었다(사용자 결정).
//     세로 2열일 땐 목록이 남는 세로를 쓰므로 영상은 16:9 그대로다.
//
//   ※ 화면이 '넓고 낮아' 전체 폭 16:9 영상이 들어갈 세로가 안 나오면, 비율을 깨는
//     대신 영상이 통째로 작아지고 좌우에 여백이 생긴다(레터박스). 예전 구현은 이
//     경우 폭을 100% 로 붙들어 박스가 2.25:1 이 되고 영상이 가로로 늘어났다.
//
// ── 카메라 목록 타일은 항상 16:9 ─────────────────────────────────────────────
// 가로 한 줄: 타일 높이 = 목록 영역 높이, 폭은 16:9 로 따라옴.
// 세로 2열:   타일 폭 = (영역폭 − 갭)/2, 높이는 16:9 로 따라옴.
//
// ── 적용 범위 ────────────────────────────────────────────────────────────────
// 개선안(A · A-1 · B)과 홈이 이 기준을 공유한다. 아래 둘은 620 이라는 값이
// 같아도 일부러 안 엮는다 — 의미가 다르고, WIDE_BP 를 옮길 때 끌려오면 안 된다:
//   · AsIsPanel  — 현행 앱 재현이자 비교 기준. 개선안을 고쳐도 As Is 는 고정.
//   · AndroidNav — 안드로이드 태스크바가 뜨는 OS 쪽 경계(우리 앱 레이아웃 아님).
//
// 주의: 홈의 Tailwind 클래스(max-w-[480px] / max-w-[700px])는 아래 HOME_W_* 를
// 문자열로 미러링한 것이다(Tailwind 임의값은 정적 문자열이라 상수를 못 받는다).
// 값을 바꾸면 app/home/page.tsx 의 클래스도 같이 고칠 것.
// ============================================================================

/** 폰 세로 ↔ 넓은 화면 경계(px). 이 값 이상이면 '넓은 화면'. */
export const WIDE_BP = 620;

/**
 * 카메라 목록이 '가로 한 줄'(가로 스크롤)일 때 타일의 최소 세로(px).
 * 세로가 짧아지면 타일이 이 아래로 줄어드는 대신 위의 단일 영상이 먼저 작아진다.
 *
 * 목록 '영역'이 아니라 타일에 건다 — 영역에 걸면 그 안의 제목·여백이 모드마다
 * (그리고 안마다 pb-4/pb-2 로) 다르게 잡아먹어서 실제 타일 최소 세로가 갈린다.
 * 타일에 직접 걸면 실시간/녹화 어느 모드든, 어느 안이든 똑같이 이 값이 된다.
 */
export const TILE_MIN_H = 48;

/**
 * 타임라인 썸네일 카드 높이(px) 범위. 카드는 항상 16:9라 폭은 여기서 따라온다.
 * 지금은 최소 = 최대 = 48 이라 사실상 고정 48(가로 85). 24 까지 줄여봤더니 너무
 * 작아서 무슨 장면인지 안 보였다. 대신 세로가 짧으면 썸네일이 줄어드는 게 아니라
 * 위의 단일 영상이 먼저 작아진다(MOTION_MIN_H).
 */
export const THUMB_MIN_H = 48;
export const THUMB_MAX_H = 48;

/**
 * 녹화 '움직임 감지' 탭(시간바 + 썸네일)의 높이(px) — A안.
 * 콘텐츠가 딱 이만큼이라 최소이자 최대다. 영역을 이 값으로 못 박아서, 세로가 짧으면
 * 시간바가 잘리는 대신 위의 영상이 먼저 줄고, 세로가 남아도 영역이 늘어나 빈 속을
 * 만들지 않는다. '카메라 목록' 탭이 가로 한 줄일 때도 같은 값을 쓴다(위 주석 참고).
 *
 * 구성: 시간바 블록(PAD_TOP 12 + RAIL_H 28 + PAD_BOTTOM 4 = 44)
 *      + 썸네일 위 4 + THUMB_MIN_H + 썸네일 아래(= PAD_TOP 12).
 */
export const MOTION_MIN_H = 44 + 4 + THUMB_MIN_H + 12;

/*
 * 가로 한 줄에서 '최소 N개 보이게' 타일 크기에 상한을 두는 방식은 폐기했다.
 * 상한을 걸면 타일이 목록 영역 높이보다 작아져 그만큼 아래가 비는데, 그 여백을
 * 단일 영상이 가져갈 수도 없다(영상은 이미 16:9 상한). 예: 360폭에서 목록 108,
 * 타일 행 84 인데 3개 상한이면 타일 57 → 27px 이 빈 공간으로 남았다.
 * 지금은 타일이 행 높이를 그대로 채운다(h-full) — 빈 공간 없음. 보이는 개수는
 * 행 높이에서 따라 나온다(좁고 낮으면 2개, 넓으면 6~14개).
 */

/**
 * 카메라 목록이 '세로 2열'일 때 목록 영역의 최소 높이(px) — 기존 값 그대로.
 * 세로 2열은 타일 가로가 영역 폭에서 나오고 세로는 거기 딸려오므로, 타일이 아니라
 * 영역에 바닥을 둔다(가로 한 줄과 달리 타일 세로를 직접 잡을 이유가 없다).
 */
export const LIST_MIN_H = 138;

/** 홈 1단(WIDE_BP 미만) 콘텐츠 최대 폭(px). 더 넓어져도 양옆 여백만 늘어난다. */
export const HOME_W_1COL = 480;

/** 홈 2단(WIDE_BP 이상) 콘텐츠 최대 폭(px) — 컬럼 280~320 두 개 + 간격 20. */
export const HOME_W_2COL = 700;
