/**
 * 가로 한 줄일 때 '한 번에 보여야 할 최소 타일 수'.
 *
 * 타일이 행 높이를 그대로 채우다 보니(h-full) 좁은 화면에서 타일이 커져 두 개
 * 남짓만 보였다 — 405 에서 타일 156×88, 목록 영역 143 이었다(사용자 지적
 * 2026-08-18: "카메라 목록은 최소 가로로 된 경우 4개는 보여야지", "가로 스크롤때
 * 최소 사이즈가 좀 큰듯"). 이제 폭에서 거꾸로 타일 높이를 잡는다:
 *   타일 폭 = (영역 폭 − 좌우 여백 − 갭×(N−1)) / N,  타일 높이 = 그 폭 ÷ (16/9)
 *
 * 예전에 이 방식을 한 번 폐기한 적이 있는데(상한을 걸면 타일이 행보다 작아져
 * 아래가 빈다), 그때는 남는 세로를 아무도 못 가져갔다. 지금은 가로 한 줄이면
 * 단일 영상이 16:9 상한을 풀고 남는 세로를 가져간다(useListLayout 의 videoFill)
 * — 빈 공간 대신 영상이 커진다.
 *
 * 넓은 화면에서는 이 규칙이 타일을 키우는 쪽으로 작동한다(750 폭이면 4개 기준
 * 타일 높이가 96) — 좁은 화면만 줄어들고, 750×832 에서 타일이 53 으로 쪼그라들던
 * 옛 문제도 같이 막힌다.
 */
