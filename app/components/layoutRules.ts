// 화면 폭에 따라 크기·배치가 바뀌는 규칙은 전부 여기 상수를 쓴다. 이 파일을
// 거치지 않고 컴포넌트 안에서 숫자를 직접 비교하지 말 것 — 예전에 480/620 두
// 기준선이 안마다 따로 굴러다니면서 같은 폭에서 안끼리 다르게 보이는 문제가
// 있었다.
//
// ── 폭 기준선은 620 하나 ─────────────────────────────────────────────────────
// 폰 세로(360~619)와 그보다 넓은 화면(태블릿·가로·폴더블, 620+)을 가르는 값.
// 폭만 보면 되는 분기는 전부 이 값을 쓴다:
//   · 홈  1단(max HOME_W_1COL) ↔ 2단(max HOME_W_2COL)   app/home/page.tsx
//
// ── 카메라 목록 방향은 폭으로 정하지 않는다 ──────────────────────────────────
// 목록이 가로 한 줄이냐 세로 2열이냐는 '남은 세로'에 달려 있어서 폭 기준선으로는
// 못 가른다. 620px 이라도 4:5(620×775)처럼 세로로 긴 화면을 가로 한 줄로 깔면
// 타일 높이가 목록 영역 높이만큼 커져 한 줄에 1개밖에 안 들어간다(실측 확인).
// 그래서 '이 영역에 어느 배치가 더 많이 보이는가'를 재서 고른다 —
// app/components/useListLayout.ts 의 useListLayout 하나를 4개 안이 공유한다.
//
// ── 단일 영상(큰 영상)은 폭·높이와 무관하게 항상 정확히 16:9 ────────────────
// 구현은 globals.css 의 .single-video-area / .single-video-box. 영역은 16:9 높이
// (56.25cqw = 프레임폭×9/16)를 기본 크기로 잡고 늘어나지는 않으며, 자리가 모자랄
// 때만 줄어든다. 박스는 그 높이를 채우되 폭이 비율을 따라가므로 어떤 경우에도
// 16:9 가 깨지지 않는다. cqw 는 .app-safe-frame 의 컨테이너 폭 기준이라 데스크톱
// 미리보기·실기기 모두에서 JS 측정 없이 정확하다.
//
// 넓은 화면에서 영상을 늘려 남는 세로를 채우는 규칙은 쓰지 않는다 — '남는 공간
// 채움 + 목록 그리드 유지 + 하단 탭 고정'이 동시에 성립하지 않아서, 셋 중 그리드와
// 탭을 택했다.
//
//   ※ 16:9 를 못 지키는 케이스: 없다. 다만 화면이 '넓고 낮아' 전체 폭 16:9 영상이
//     들어갈 세로가 안 나오면, 비율을 깨는 대신 영상이 통째로 작아지고 좌우에
//     여백이 생긴다(레터박스). 프리셋 기준 864×648·1080×780 이 여기 해당하고,
//     360·405·480·620·750·780 은 폭을 꽉 채운다. 예전 구현은 이 경우 폭을 100%
//     로 붙들어 박스가 2.25:1 이 되고 영상이 가로로 늘어났다(object-fill).
//
// ── 카메라 목록 타일은 항상 16:9 ─────────────────────────────────────────────
// 가로 한 줄: 타일 높이 = 목록 영역 높이, 폭은 16:9 로 따라옴.
// 세로 2열:   타일 폭 = (영역폭 − 갭)/2, 높이는 16:9 로 따라옴.
//
// ── 적용 범위 ────────────────────────────────────────────────────────────────
// 개선안(A · A-1 · A-2 · B)과 홈이 이 기준을 공유한다. 아래 둘은 620 이라는 값이
// 같아도 일부러 안 엮는다 — 의미가 다르고, WIDE_BP 를 옮길 때 끌려오면 안 된다:
//   · AsIsPanel  — 현행 앱 재현이자 비교 기준. 개선안을 고쳐도 As Is 는 고정.
//   · AndroidNav — 안드로이드 태스크바가 뜨는 OS 쪽 경계(우리 앱 레이아웃 아님).
//
// 주의: 홈의 Tailwind 클래스(max-w-[480px] / max-w-[700px])는 아래 HOME_W_* 를
// 문자열로 미러링한 것이다(Tailwind 임의값은 정적 문자열이라 상수를 못 받는다).
// 값을 바꾸면 app/home/page.tsx 의 클래스도 같이 고칠 것.
// ============================================================================

/** 폰 세로 ↔ 넓은 화면 경계(px). 이 값 이상이면 '넓은 화면'. */
export const WIDE_BP = 620;

/**
 * 카메라 목록 '타일 행'의 최소 높이(px). 세로가 짧은 화면에서 타일이 이 아래로
 * 줄어드는 대신 위의 단일 영상이 먼저 작아진다.
 *
 * 목록 '영역'이 아니라 타일 행에 건다 — 영역에 걸면 그 안의 제목·여백이 모드마다
 * 다르게 잡아먹어서 실시간/녹화의 실제 타일 최소 높이가 갈린다. 타일에 직접 걸면
 * 어느 모드든 최소값이 똑같이 이 값이 된다.
 */
export const TILE_MIN_H = 48;

/** 홈 1단(WIDE_BP 미만) 콘텐츠 최대 폭(px). 더 넓어져도 양옆 여백만 늘어난다. */
export const HOME_W_1COL = 480;

/** 홈 2단(WIDE_BP 이상) 콘텐츠 최대 폭(px) — 컬럼 280~320 두 개 + 간격 20. */
export const HOME_W_2COL = 700;
