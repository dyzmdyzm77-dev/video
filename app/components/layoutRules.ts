/** 폰 세로 ↔ 넓은 화면 경계(px). 이 값 이상이면 '넓은 화면'. */
export const WIDE_BP = 620;

/**
 * 단일 영상 화면에서 '오른쪽 세로 패널'로 넘어가는 화면 비율(가로/세로).
 * 이 값 이상이면 카메라 목록·움직임 감지가 화면 아래 가로 스트립이 아니라 오른쪽 끝
 * 세로 패널로 간다(탭도 패널 안 위쪽으로). 영상은 왼쪽 컬럼을 쓴다.
 *
 * ── 왜 폭이 아니라 비율인가 ──────────────────────────────────────────────────
 * 영상이 16:9 라, 세로가 모자라는 화면에서는 세로 1px 을 잃으면 가로가 1.78px 줄어든다.
 * 하단 스트립은 세로 152(탭 43 + 선 1 + MOTION_MIN_H 108)를 먹으므로, 그런 화면에선
 * 영상 폭을 270px 이나 깎는다. 반대로 세로로 긴 화면은 영상이 이미 폭에 꽉 차 있어서
 * 스트립을 넣어도 손해가 0 이다. 실측:
 *
 *     620×780   영상 폭 620 → 620   (−0px)    스트립이 손해 없음
 *     780×780          780 → 728   (−51px)
 *     864×648          764 → 494   (−270px)   화면의 1/3
 *    1080×780          999 → 728   (−270px)
 *
 * 즉 '가로 비율이 길다' = '영상이 세로에 갇혔다' = '하단 스트립이 영상을 크게 깎는다'
 * 가 같은 말이라, 비율을 재는 게 곧 스트립의 손해를 재는 것이다.
 *
 * 폭으로는 못 가른다 — 정확한 경계 폭이 세로에 따라 크게 움직인다(세로 648 이면 714,
 * 780 이면 949, 792 면 970). 비율로 보면 1.10~1.23 으로 거의 안 움직여서 값 하나로
 * 근사가 된다. 예전에 1080 이라는 폭 기준선을 썼는데, 그건 프리셋에서 우연히 맞은
 * 값이지 원칙에서 나온 숫자가 아니었다.
 *
 * ── 왜 19:16(1.1875) 인가 ───────────────────────────────────────────────────
 * 프리셋 비율: 360×780=0.46 · 480×780=0.62 · 405×648=0.63 · 620×780=0.79 ·
 * 750×832=0.90 · 780×780=1.00 ‖ 864×648=1.33 · 1080×792=1.36 · 1080×780=1.38.
 * 1.00 과 1.33 사이가 통째로 비어 있어 그 안이면 프리셋 결과는 같다(780×780 은
 * 하단 스트립·864×648 은 패널 — 1.25 여도 1.1875 여도 동일).
 *
 * 처음엔 1.25(=5:4)로 잡았는데, 정사각에 가까운 화면(5:4 근처)에서 하단
 * 스트립인 채로 남으면 16:9 영상이 그 안에서 유난히 가로로 넓적해 보인다는
 * 지적으로 낮췄다. 1.1 로 한번 낮췄다가, 실제로 보니 그건 너무 이르게
 * 넘어가더라는 피드백으로 19:16(1.1875) 로 다시 조정했다(사용자 결정) — 이
 * 근처 화면을 조금 더 일찍 패널로 넘겨, 패널 쪽 세로 확장(빈 공간 없이 남는
 * 세로를 전부 채운다 — 아래 참고)으로 정사각형에 더 가깝게 보이게 한다.
 * 비율은 기기 크기로만 정해지므로 헤더·스트립 높이를 바꿔도 이 판정은 안 흔들린다.
 *
 * 패널 안 '움직임 감지'는 가로 시간바가 아니라 세로 타임라인을 쓴다(SideEventTimeline).
 * 가로 시간바는 폭이 넓어야 쓸 만한데 패널은 SIDE_PANEL_W 밖에 안 된다.
 *
 * 적용 범위는 A안 단일 영상 화면. 다채널(그리드)은 그대로 둔다.
 */
export const SIDE_PANEL_RATIO = 19 / 16;

/**
 * 오른쪽 세로 패널 폭(px). 목록 타일은 16:9 라 이 폭에서 타일 세로가 따라 나온다.
 * 좁힐수록 왼쪽 영상이 넓어져 덜 눌린다 — 1080×780 기준 320:1.35 / 260:1.46 / 220:1.53.
 *
 * 바닥은 감지 탭 세로 타임라인의 카드가 정한다: 시간 라벨 100 + 여백 12 + 썸네일 폭
 * (THUMB_MIN_H 48 의 16:9 = 85) = 오른쪽 끝 197. 여기에 오른쪽 여백을 조금 남긴 값이
 * 220 이다. 더 줄이려면 라벨 띠(100) 나 썸네일부터 손봐야 한다.
 */
export const SIDE_PANEL_W = 220;

