// 화면 폭에 따라 크기·배치가 바뀌는 규칙은 전부 여기 상수를 쓴다. 이 파일을
// 거치지 않고 컴포넌트 안에서 숫자를 직접 비교하지 말 것 — 예전에 480/620 두
// 기준선이 안마다 따로 굴러다니면서 같은 폭에서 안끼리 다르게 보이는 문제가
// 있었다.
//
// ── 폭 기준선은 620 하나 ─────────────────────────────────────────────────────
// 폰 세로(360~619)와 그보다 넓은 화면(태블릿·가로·폴더블, 620+)을 가르는 값.
// 폭만 보면 되는 분기는 전부 이 값을 쓴다:
//   · 홈  1단(max HOME_W_1COL) ↔ 2단(max HOME_W_2COL)   app/home/page.tsx
//
// ── 카메라 목록 방향은 폭으로 정하지 않는다 ──────────────────────────────────
// 목록이 가로 한 줄이냐 세로 2열이냐는 '남은 세로'에 달려 있어서 폭 기준선으로는
// 못 가른다(620px 이라도 4:5 처럼 세로로 긴 화면은 세로 2열이 넉넉히 들어간다).
// 기준: 세로 2열로 '완전히 보이는 2개 + 반쯤 보이는 2개'(= 1.5줄)에 못 미치면
// 가로 한 줄로 넘어간다. app/components/useListLayout.ts 하나를 안들이 공유한다.
//
// 가로 한 줄일 때 목록 영역 높이 = '움직임 감지' 탭 높이(MOTION_MIN_H). '최소'가
// 아니라 '정확히 그 값'으로 못 박는다 — 두 탭 스트립이 1px 도 안 어긋나야 하므로,
// 세로가 남는 화면(620×780·750×832)에서 목록만 flex-1 로 늘어나면 안 된다.
// 못 박고 남는 세로는 단일 영상이 가져간다(아래 참고) — 스트립 아래에 빈 공간을
// 남기지 않는다. 실시간·녹화 모두 같다.
// A안 얘기다 — A-1·B안의 감지 탭은 '세로 타임라인'이라 영역을 채우는 게 맞고,
// 그래서 useListLayout 에 motionH 를 안 넘긴다(못 박지도, 영상을 늘리지도 않는다).
//
// ── 단일 영상(큰 영상)은 기본이 정확히 16:9 ─────────────────────────────────
// 구현은 globals.css 의 .single-video-area / .single-video-box. 영역은 16:9 높이
// (56.25cqw = 프레임폭×9/16)를 기본 크기로 잡고 늘어나지는 않으며, 자리가 모자랄
// 때만 줄어든다. 박스는 그 높이를 채우되 폭이 비율을 따라가므로 비율이 안 깨진다.
// cqw 는 .app-safe-frame 의 컨테이너 폭 기준이라 데스크톱 미리보기·실기기 모두에서
// JS 측정 없이 정확하다.
//
//   ※ 예외 — 카메라 목록이 가로 스크롤(가로 한 줄)일 때는 16:9 를 넘겨 늘어난다.
//     목록 스트립을 MOTION_MIN_H 로 못 박고 남는 세로를 영상이 다 가져가기 때문이다
//     (useListLayout 이 .single-video-area 의 flex-grow / max-height 를 푼다).
//     프리셋 기준 620×780 에서 1.52:1(녹화)·1.22:1(실시간)까지 세로로 늘어난다.
//     예전엔 '비율 유지'를 택해 그 자리를 빈 공간으로 뒀는데, 감지 탭과 목록 탭이
//     같은 높이여야 한다는 요구와 겹치면서 빈 공간이 눈에 띄어 뒤집었다(사용자 결정).
//     세로 2열일 땐 목록이 남는 세로를 쓰므로 영상은 16:9 그대로다.
//
//   ※ 화면이 '넓고 낮아' 전체 폭 16:9 영상이 들어갈 세로가 안 나오면, 비율을 깨는
//     대신 영상이 통째로 작아지고 좌우에 여백이 생긴다(레터박스). 예전 구현은 이
//     경우 폭을 100% 로 붙들어 박스가 2.25:1 이 되고 영상이 가로로 늘어났다.
//
// ── 카메라 목록 타일은 항상 16:9 ─────────────────────────────────────────────
// 가로 한 줄: 타일 높이 = 목록 영역 높이, 폭은 16:9 로 따라옴.
// 세로 2열:   타일 폭 = (영역폭 − 갭)/2, 높이는 16:9 로 따라옴.
